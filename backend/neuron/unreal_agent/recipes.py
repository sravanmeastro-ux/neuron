def parse_crash(text: str) -> dict[str, Any]:
    raw = text or ""
    findings: list[dict[str, Any]] = []
    import re
    for m in re.finditer(r"(Fatal error|Assertion failed|Unhandled Exception)[:\s]+(.+)", raw, re.I):
        findings.append({"kind": "fatal", "message": m.group(0)[:300]})
    for m in re.finditer(r"(UE4Editor|UnrealEditor)[^\n]+", raw):
        findings.append({"kind": "module", "message": m.group(0)[:200]})
    for m in re.finditer(r"([A-Za-z0-9_]+::[A-Za-z0-9_]+)\(\)", raw):
        findings.append({"kind": "symbol", "message": m.group(1)})
    for m in re.finditer(r"Log[A-Za-z]+:\s*Error:\s*(.+)", raw):
        findings.append({"kind": "log_error", "message": m.group(1)[:240]})
    primary = findings[0]["message"] if findings else "No clear crash signature — paste Saved/Logs crash context."
    advice = [
        "Open the matching .pdb symbols if a callstack is truncated.",
        "Reproduce with `-log` and check `Saved/Logs/*.log`.",
        "Check recent C++ changes around asserted pointers (IsValid).",
        "Disable suspect plugins; binary-search maps.",
    ]
    path = write_text("logs/last_crash_analysis.md", f"# Crash analysis\n\nPrimary: {primary}\n\n" + "\n".join(f"- {a}" for a in advice))
    return {"findings": findings[:30], "primary": primary, "advice": advice, "path": str(path)}
