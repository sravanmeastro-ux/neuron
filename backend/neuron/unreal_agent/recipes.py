def script_third_person_character(name: str = "TP_Character") -> tuple[str, str]:
    """Editor Python that scaffolds a Character Blueprint + notes for GameMode."""
    src = _py_header() + f'''
char_path = "/Game/NEURON/{name}"
factory = unreal.BlueprintFactory()
factory.set_editor_property("ParentClass", unreal.Character)
asset_tools = unreal.AssetToolsHelpers.get_asset_tools()
try:
    bp = asset_tools.create_asset("{name}", "/Game/NEURON", unreal.Blueprint, factory)
    log(f"Created Character Blueprint: {{bp.get_path_name() if bp else char_path}}")
except Exception as exc:
    log(f"Blueprint create note: {{exc}} — ensure /Game/NEURON exists or create folder in Content Browser.")

# Add a simple camera boom / follow camera components via default subobject guidance
log("Next: open {name}, add SpringArm + Camera, set Auto Possess Player to Player 0.")
log("NEURON_UNREAL_OK third_person_character")
'''
    path = write_text(f"scripts/tp_character_{name}.py", src)
    # Also emit C++ stub
    h = f'''#pragma once
#include "CoreMinimal.h"
#include "GameFramework/Character.h"
#include "Camera/CameraComponent.h"
#include "GameFramework/SpringArmComponent.h"
#include "{name}.generated.h"

UCLASS()
class A{name} : public ACharacter
{{
	GENERATED_BODY()
public:
	A{name}();
protected:
	UPROPERTY(VisibleAnywhere, BlueprintReadOnly, Category="Camera")
	USpringArmComponent* CameraBoom;
	UPROPERTY(VisibleAnywhere, BlueprintReadOnly, Category="Camera")
	UCameraComponent* FollowCamera;
	virtual void SetupPlayerInputComponent(class UInputComponent* PlayerInputComponent) override;
}};
'''
    cpp = f'''#include "{name}.h"
#include "GameFramework/Controller.h"
#include "EnhancedInputComponent.h"

A{name}::{name}()
{{
	PrimaryActorTick.bCanEverTick = false;
	CameraBoom = CreateDefaultSubobject<USpringArmComponent>(TEXT("CameraBoom"));
	CameraBoom->SetupAttachment(RootComponent);
	CameraBoom->TargetArmLength = 400.f;
	CameraBoom->bUsePawnControlRotation = true;
	FollowCamera = CreateDefaultSubobject<UCameraComponent>(TEXT("FollowCamera"));
	FollowCamera->SetupAttachment(CameraBoom, USpringArmComponent::SocketName);
	FollowCamera->bUsePawnControlRotation = false;
}}

void A{name}::SetupPlayerInputComponent(UInputComponent* PlayerInputComponent)
{{
	Super::SetupPlayerInputComponent(PlayerInputComponent);
	// Bind Move/Look via Enhanced Input in the editor or project defaults.
}}
'''
    write_text(f"cpp/{name}.h", h)
    write_text(f"cpp/{name}.cpp", cpp)
    return str(path), src


