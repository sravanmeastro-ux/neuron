def script_import(path: str) -> str:
    p = Path(path).as_posix()
    out = (assets_root() / "exports" / "imported.blend").as_posix()
    return _header() + f'''
_ensure_object_mode()
fp = r"{p}"
low = fp.lower()
if low.endswith('.obj'):
    bpy.ops.wm.obj_import(filepath=fp) if hasattr(bpy.ops.wm, 'obj_import') else bpy.ops.import_scene.obj(filepath=fp)
elif low.endswith('.fbx'):
    bpy.ops.import_scene.fbx(filepath=fp)
elif low.endswith('.gltf') or low.endswith('.glb'):
    bpy.ops.import_scene.gltf(filepath=fp)
elif low.endswith('.stl'):
    bpy.ops.wm.stl_import(filepath=fp) if hasattr(bpy.ops.wm, 'stl_import') else bpy.ops.import_mesh.stl(filepath=fp)
elif low.endswith('.blend'):
    with bpy.data.libraries.load(fp) as (data_from, data_to):
        data_to.objects = data_from.objects
    for obj in data_to.objects:
        if obj is not None:
            bpy.context.collection.objects.link(obj)
else:
    raise RuntimeError("Unsupported import format: " + fp)
bpy.ops.wm.save_as_mainfile(filepath=r"{out}")
print("NEURON_BLENDER_OK import -> {out}")
'''


def script_export(path: str, fmt: str = "glb") -> str:
    p = Path(path).as_posix()
    fmt = (fmt or "glb").lower()
    return _header() + f'''
_ensure_object_mode()
fp = r"{p}"
fmt = "{fmt}"
bpy.ops.object.select_all(action='SELECT')
if fmt in ("glb", "gltf"):
    bpy.ops.export_scene.gltf(filepath=fp, export_format='GLB' if fmt=='glb' else 'GLTF_SEPARATE')
elif fmt == "fbx":
    bpy.ops.export_scene.fbx(filepath=fp)
elif fmt == "obj":
    bpy.ops.wm.obj_export(filepath=fp) if hasattr(bpy.ops.wm, 'obj_export') else bpy.ops.export_scene.obj(filepath=fp)
elif fmt == "stl":
    bpy.ops.wm.stl_export(filepath=fp) if hasattr(bpy.ops.wm, 'stl_export') else bpy.ops.export_mesh.stl(filepath=fp)
else:
    bpy.ops.wm.save_as_mainfile(filepath=fp)
print("NEURON_BLENDER_OK export_" + fmt + " -> " + fp)
'''


def script_texture(name: str = "NeuronTex") -> str:
    """Procedural texture via noise + color ramp on Principled BSDF."""
    return script_material(name=name, style="texture")


def list_assets() -> dict[str, Any]:
    root = assets_root()
    files = []
    for sub in ("exports", "renders", "scripts", "assets", "imports"):
        d = root / sub
        if not d.is_dir():
            continue
        for f in sorted(d.iterdir()):
            if f.is_file():
                files.append({"folder": sub, "name": f.name, "path": str(f), "bytes": f.stat().st_size})
    return {"root": str(root), "files": files[-80:], "count": len(files)}
