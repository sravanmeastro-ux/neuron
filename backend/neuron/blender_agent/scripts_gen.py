def script_soda_can(*, name: str = "SodaCan") -> str:
    out = (assets_root() / "exports" / f"{name}.blend").as_posix()
    return _header() + f'''
_ensure_object_mode()
# Realistic soda can: body cylinder + top/bottom + metallic material
bpy.ops.mesh.primitive_cylinder_add(vertices=64, radius=0.033, depth=0.122, location=(0, 0, 0.061))
body = bpy.context.active_object
body.name = "{name}_Body"

# Top lid (slightly inset)
bpy.ops.mesh.primitive_cylinder_add(vertices=64, radius=0.032, depth=0.004, location=(0, 0, 0.124))
top = bpy.context.active_object
top.name = "{name}_Top"

# Bottom
bpy.ops.mesh.primitive_cylinder_add(vertices=64, radius=0.032, depth=0.004, location=(0, 0, 0.002))
bottom = bpy.context.active_object
bottom.name = "{name}_Bottom"

# Tab (simple cube scaled)
bpy.ops.mesh.primitive_cube_add(size=0.01, location=(0.0, 0.012, 0.127))
tab = bpy.context.active_object
tab.name = "{name}_Tab"
tab.scale = (1.6, 0.6, 0.15)

def metal_mat(mat_name, base=(0.75, 0.75, 0.78, 1.0), rough=0.25, metal=1.0):
    mat = bpy.data.materials.new(name=mat_name)
    mat.use_nodes = True
    nt = mat.node_tree
    bsdf = nt.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs["Base Color"].default_value = base
        bsdf.inputs["Metallic"].default_value = metal
        bsdf.inputs["Roughness"].default_value = rough
    return mat

body_mat = metal_mat("{name}_Metal", (0.8, 0.12, 0.12, 1.0), rough=0.22)
top_mat = metal_mat("{name}_Aluminum", (0.7, 0.7, 0.72, 1.0), rough=0.18)
for obj, mat in ((body, body_mat), (top, top_mat), (bottom, top_mat), (tab, top_mat)):
    if obj.data.materials:
        obj.data.materials[0] = mat
    else:
        obj.data.materials.append(mat)

# Join
for obj in (top, bottom, tab):
    obj.select_set(True)
body.select_set(True)
bpy.context.view_layer.objects.active = body
bpy.ops.object.join()
body.name = "{name}"

# Camera + light
if "Camera" not in bpy.data.objects:
    bpy.ops.object.camera_add(location=(0.25, -0.35, 0.18))
cam = bpy.data.objects["Camera"]
cam.location = (0.25, -0.35, 0.18)
cam.rotation_euler = Euler((math.radians(72), 0, math.radians(35)), 'XYZ')
bpy.context.scene.camera = cam

if "Light" not in bpy.data.objects:
    bpy.ops.object.light_add(type='AREA', location=(0.4, -0.2, 0.5))
light = bpy.data.objects.get("Light") or bpy.context.active_object
light.data.energy = 250
light.data.size = 0.4

bpy.ops.wm.save_as_mainfile(filepath=r"{out}")
print("NEURON_BLENDER_OK soda_can -> {out}")
'''


def script_create_object(kind: str = "cube", name: str = "NeuronObject") -> str:
    kind = (kind or "cube").lower()
    ops = {
        "cube": "bpy.ops.mesh.primitive_cube_add(size=2, location=(0,0,1))",
        "sphere": "bpy.ops.mesh.primitive_uv_sphere_add(radius=1, location=(0,0,1))",
        "cylinder": "bpy.ops.mesh.primitive_cylinder_add(radius=1, depth=2, location=(0,0,1))",
        "plane": "bpy.ops.mesh.primitive_plane_add(size=4, location=(0,0,0))",
        "torus": "bpy.ops.mesh.primitive_torus_add(location=(0,0,1))",
        "cone": "bpy.ops.mesh.primitive_cone_add(radius1=1, depth=2, location=(0,0,1))",
        "monkey": "bpy.ops.mesh.primitive_monkey_add(location=(0,0,1))",
    }
    op = ops.get(kind, ops["cube"])
    out = (assets_root() / "exports" / f"{name}.blend").as_posix()
    return _header() + f'''
_ensure_object_mode()
{op}
obj = bpy.context.active_object
obj.name = "{name}"
bpy.ops.wm.save_as_mainfile(filepath=r"{out}")
print("NEURON_BLENDER_OK create_{kind} -> {out}")
'''


def script_material(name: str = "NeuronMaterial", style: str = "procedural") -> str:
    out = (assets_root() / "exports" / f"{name}.blend").as_posix()
    return _header() + f'''
_ensure_object_mode()
# Target active mesh or create a sphere
if not bpy.context.active_object or bpy.context.active_object.type != 'MESH':
    bpy.ops.mesh.primitive_uv_sphere_add(radius=1, location=(0,0,1))
obj = bpy.context.active_object
mat = bpy.data.materials.new(name="{name}")
mat.use_nodes = True
nt = mat.node_tree
nodes = nt.nodes
links = nt.links
nodes.clear()
out_n = nodes.new("ShaderNodeOutputMaterial")
bsdf = nodes.new("ShaderNodeBsdfPrincipled")
noise = nodes.new("ShaderNodeTexNoise")
colorramp = nodes.new("ShaderNodeValToRGB")
noise.inputs["Scale"].default_value = 6.0
noise.inputs["Detail"].default_value = 8.0
colorramp.color_ramp.elements[0].color = (0.05, 0.08, 0.2, 1)
colorramp.color_ramp.elements[1].color = (0.7, 0.75, 0.9, 1)
links.new(noise.outputs["Fac"], colorramp.inputs["Fac"])
links.new(colorramp.outputs["Color"], bsdf.inputs["Base Color"])
bsdf.inputs["Roughness"].default_value = 0.35
bsdf.inputs["Metallic"].default_value = 0.15
links.new(bsdf.outputs["BSDF"], out_n.inputs["Surface"])
if obj.data.materials:
    obj.data.materials[0] = mat
else:
    obj.data.materials.append(mat)
bpy.ops.wm.save_as_mainfile(filepath=r"{out}")
print("NEURON_BLENDER_OK material_{style} -> {out}")
'''


def script_geometry_nodes(name: str = "NeuronGeoNodes") -> str:
    out = (assets_root() / "exports" / f"{name}.blend").as_posix()
    return _header() + f'''
_ensure_object_mode()
bpy.ops.mesh.primitive_plane_add(size=4, location=(0,0,0))
obj = bpy.context.active_object
obj.name = "{name}_Grid"

mod = obj.modifiers.new(name="{name}", type='NODES')
node_group = bpy.data.node_groups.new(name="{name}", type='GeometryNodeTree')
mod.node_group = node_group
nodes = node_group.nodes
links = node_group.links
nodes.clear()
# Blender 3+ geometry nodes interface
try:
    node_group.interface.new_socket(name="Geometry", in_out='INPUT', socket_type='NodeSocketGeometry')
    node_group.interface.new_socket(name="Geometry", in_out='OUTPUT', socket_type='NodeSocketGeometry')
except Exception:
    pass
nin = nodes.new("NodeGroupInput")
nout = nodes.new("NodeGroupOutput")
subdiv = nodes.new("GeometryNodeSubdivisionSurface")
displace = nodes.new("GeometryNodeSetPosition")
noise = nodes.new("ShaderNodeTexNoise")
nin.location = (-400, 0)
subdiv.location = (-150, 0)
noise.location = (-150, -200)
displace.location = (100, 0)
nout.location = (350, 0)
noise.inputs["Scale"].default_value = 4.0
links.new(nin.outputs[0], subdiv.inputs["Mesh"])
links.new(subdiv.outputs["Mesh"], displace.inputs["Geometry"])
# Offset via noise on Z — simplified: pass through if sockets mismatch
try:
    links.new(displace.outputs["Geometry"], nout.inputs[0])
except Exception:
    links.new(subdiv.outputs["Mesh"], nout.inputs[0])
bpy.ops.wm.save_as_mainfile(filepath=r"{out}")
print("NEURON_BLENDER_OK geometry_nodes -> {out}")
'''


